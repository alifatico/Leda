export type Dict = typeof it;
export type Locale = "it" | "en";
export const dicts: Record<Locale, Dict> = { it, en: en as Dict };

type Leaves<T, P extends string = ""> = {
  [K in keyof T & string]: T[K] extends string ? `${P}${K}` : Leaves<T[K], `${P}${K}.`>;
}[keyof T & string];
export type TKey = Leaves<Dict>;

export function lookup(dict: Dict, key: TKey, vars?: Record<string, string | number>): string {
  const raw = key.split(".").reduce<unknown>((acc, part) => (acc && typeof acc === "object" ? (acc as Record<string, unknown>)[part] : undefined), dict);
  let out = typeof raw === "string" ? raw : key;
  if (vars) for (const [k, v] of Object.entries(vars)) out = out.replaceAll(`{${k}}`, String(v));
  return out;
}
